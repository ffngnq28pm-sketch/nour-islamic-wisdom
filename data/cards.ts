export function getDailyCard(): WisdomCard {
  const freeCards = CARDS.filter((c) => !c.premium);
  const dayOfYear = Math.floor(
    (Date.now() - new Date(new Date().getFullYear(), 0, 0).getTime()) / 86400000
  );
  return freeCards[dayOfYear % freeCards.length];
}
